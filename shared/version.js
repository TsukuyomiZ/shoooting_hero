// 顯示用的版本名稱：BETA v1.2、正式版就只有 v1.2
export const versionLabel = ({ channel, number } = VERSION) => (channel ? `${channel} v${number}` : `v${number}`);

// package.json 的 version（semver）：1.2 BETA → 1.2.0-beta、1.2.1 → 1.2.1
export function semverOf({ channel, number } = VERSION) {
  const parts = String(number).split('.');
  while (parts.length < 3) parts.push('0');
  return parts.join('.') + (channel ? `-${channel.toLowerCase()}` : '');
}
