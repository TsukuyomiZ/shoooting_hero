const branch = ({ x0, x1, y, root }) => {
  const r = root === 'right';
  const thick = (t) => Math.round(6 + 16 * (r ? t : 1 - t));   // t = 0（左端）~ 1（右端）的厚度
  const xs = [x0, x0 + (x1 - x0) * 0.25, (x0 + x1) / 2, x0 + (x1 - x0) * 0.75, x1];
  return [[x0, y], [x1, y], ...xs.slice().reverse().map(x => [Math.round(x), y + thick((x - x0) / (x1 - x0))])];
};

